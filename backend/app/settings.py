"""Configuration read from the environment and `.env` (spec 12.3).

Every timing here is provisional until contract SO101-37 lands (Q11).
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic_settings import BaseSettings, SettingsConfigDict

BACKEND_DIR = Path(__file__).resolve().parent.parent

# LIBERO camera names, used as-is end to end (communication-plan §3.4).
CAMERAS = ("agentview", "wrist")


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="SO101_", env_file=".env", env_file_encoding="utf-8", extra="ignore"
    )

    be_host: str = "0.0.0.0"
    be_port: int = 8001

    # Only the LIBERO Operator API is supported (communication-plan §3.1). Dev and tests
    # use the real sim in fake mode: `python server.py --backend fake`.
    sim_link: Literal["real"] = "real"
    sim_url: str = "http://127.0.0.1:8000"
    # LIBERO Operator API token generated by libero_board/server.py.
    operator_token_file: Path = Path("../libero_board/runtime/.operator-token")
    # Demo tasks proposed by IoT (Q2), first one is the default. "suite:task_id", comma separated.
    libero_tasks: str = "libero_spatial:0,libero_object:0"
    # Task a REST reset uses when the body names none (= the first demo task).
    libero_suite: str = "libero_spatial"
    libero_task_id: int = 0
    libero_init_state: int = 0
    sim_poll_hz: float = 10.0
    sim_timeout_ms: int = 2000
    # Board RESET can take 3–15 s; its operator contract requires >= 30 s. Also the HTTP
    # timeout of `stop`: a stop sent during a reset waits for the reset to finish (Q5).
    libero_reset_timeout_ms: int = 30000
    # Q1: the Board runner has no "wait for command" mode yet. True = `command` needs
    # `session_active`. False (dev only) = the BE resets anyway and the operator starts
    # the runner with `--no-reset` by hand. TODO(Q1): drop once the waiting mode exists.
    require_board_session: bool = True
    # One /api/state call may not eat the whole offline budget (see README, "Khác với spec").
    sim_poll_timeout_ms: int = 500

    data_dir: Path = Path("./data")
    fe_dist_dir: Path = BACKEND_DIR.parent / "dist"

    mode: Literal["dev", "scored"] = "dev"
    evidence_class: str = "laptop"
    allowed_origins: str = "http://localhost:5173,http://localhost:8001"

    status_period_ms: int = 500
    ping_period_ms: int = 1000

    camera_preview: bool = True
    camera_fps: float = 10.0
    camera_meta_ms: int = 250

    ws_queue_max: int = 256
    writer_queue_max: int = 20000
    quarantine_max_rows: int = 1000
    history_limit: int = 50

    @property
    def origins(self) -> list[str]:
        return [o.strip().rstrip("/") for o in self.allowed_origins.split(",") if o.strip()]

    @property
    def libero_task_list(self) -> list[tuple[str, int]]:
        """`libero_tasks` parsed; entries that do not read "suite:int" are skipped."""
        out: list[tuple[str, int]] = []
        for item in self.libero_tasks.split(","):
            suite, _, task = item.strip().partition(":")
            if suite and task.strip().isdigit():
                out.append((suite.strip(), int(task)))
        return out

    @property
    def db_path(self) -> Path:
        return self.data_dir / "so101.db"

    @property
    def runs_dir(self) -> Path:
        return self.data_dir / "runs"


@lru_cache
def get_settings() -> Settings:
    return Settings()
